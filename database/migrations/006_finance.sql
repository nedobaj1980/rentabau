CREATE TABLE IF NOT EXISTS fin_settings (
 id TINYINT UNSIGNED PRIMARY KEY, settings_json LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fin_sequences (
 sequence_key VARCHAR(30) PRIMARY KEY, last_number INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fin_invoices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 number VARCHAR(40) NOT NULL UNIQUE,
 reservation_id BIGINT UNSIGNED NOT NULL,
 source_key VARCHAR(80) NULL UNIQUE,
 kind VARCHAR(20) NOT NULL DEFAULT 'invoice',
 original_invoice_id BIGINT UNSIGNED NULL UNIQUE,
 customer_key VARCHAR(300) NOT NULL,
 customer_name VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL,
 customer_address TEXT NOT NULL,
 issue_date DATE NOT NULL, due_date DATE NOT NULL,
 net_cents BIGINT NOT NULL, tax_cents BIGINT NOT NULL, total_cents BIGINT NOT NULL,
 items_json LONGTEXT NOT NULL, seller_json LONGTEXT NOT NULL, reservation_json LONGTEXT NOT NULL,
 notes TEXT NOT NULL,
 pdf_blob MEDIUMBLOB NOT NULL, pdf_sha256 CHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY fin_invoice_reservation (reservation_id), KEY fin_invoice_date (issue_date),
 FOREIGN KEY (reservation_id) REFERENCES reservations(id),
 FOREIGN KEY (original_invoice_id) REFERENCES fin_invoices(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fin_payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 invoice_id BIGINT UNSIGNED NOT NULL, refund_of BIGINT UNSIGNED NULL,
 amount_cents BIGINT NOT NULL, date DATE NOT NULL,
 method VARCHAR(50) NOT NULL, reference VARCHAR(250) NOT NULL,
 request_key VARCHAR(80) NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (invoice_id) REFERENCES fin_invoices(id),
 FOREIGN KEY (refund_of) REFERENCES fin_payments(id),
 KEY fin_payment_date (date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fin_expenses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 supplier VARCHAR(255) NOT NULL, description TEXT NOT NULL,
 amount_cents BIGINT NOT NULL, date DATE NOT NULL,
 category VARCHAR(100) NOT NULL, payment_method VARCHAR(50) NOT NULL,
 receipt_blob MEDIUMBLOB NULL, receipt_mime VARCHAR(50) NULL, receipt_name VARCHAR(255) NULL,
 request_key VARCHAR(80) NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY fin_expense_date (date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fin_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 action VARCHAR(80) NOT NULL, entity VARCHAR(80) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL,
 details_json LONGTEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY fin_event_entity (entity,entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS fin_deliveries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, invoice_id BIGINT UNSIGNED NOT NULL,
 recipient VARCHAR(255) NOT NULL, status VARCHAR(40) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (invoice_id) REFERENCES fin_invoices(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
